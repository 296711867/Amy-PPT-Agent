export type IpcInvokeChannel = (typeof IPC_INVOKE_CHANNELS)[number]
export type IpcEventChannel = (typeof IPC_EVENT_CHANNELS)[number]

const invokeChannelSet = new Set<string>(IPC_INVOKE_CHANNELS)
const eventChannelSet = new Set<string>(IPC_EVENT_CHANNELS)

export function isAllowedIpcInvokeChannel(value: string): value is IpcInvokeChannel {
  return invokeChannelSet.has(value)
}

export function isAllowedIpcEventChannel(value: string): value is IpcEventChannel {
  return eventChannelSet.has(value)
}
